using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Nodes;

namespace RPGGame.Data
{
    /// <summary>
    /// ITEM MODS tab (<c>ItemMods.json</c>) and RARITY tab (<c>RarityTable.json</c>) for the item roller
    /// (Documentation/ITEM_GENERATION_REDESIGN_2026-11-14.md).
    /// ITEM MODS: one row per tier; the family columns repeat on every row of the family (rows with the same
    /// <c>family</c> are one family, tiers in row order). Lists are comma-separated; <c>slotLevel</c> is
    /// <c>weapon:17, chest:5</c>.
    /// RARITY: one row per rarity; pool line counts as <c>{pool}Min</c> / <c>{pool}Max</c> columns.
    /// </summary>
    public static partial class JsonArraySheetConverter
    {
        public static readonly string[] ItemModsCanonicalHeaders = JsonArraySheetSchemas.ItemModsCanonicalHeaders;
        public static readonly string[] RarityCanonicalHeaders = JsonArraySheetSchemas.RarityCanonicalHeaders;

        internal const string ItemModsDocText =
            "Item mod families (Documentation/ITEM_GENERATION_REDESIGN_2026-11-14.md). Generated by " +
            "Scripts/build-item-mods.py, then hand-edited. pool: material|stat|mechanic|action. kind: stat " +
            "(StatBonus of statType), mod (clone of the Modifications/PrefixMaterialQuality template), suffix " +
            "(clone of a StatBonuses row), slots (+combo strip slots). Tier: keyword, min/max value, level (item " +
            "level needed; slotLevel overrides per slot), weight, maxRarity (highest item rarity that can roll it; " +
            "'Common' tiers are the common-only highs), slots (optional per-tier slot limit).";


        // ---------- ITEM MODS ----------

        private static List<IList<object>> BuildItemModsPushValueRows(string jsonFileText)
        {
            var rows = new List<IList<object>> { ItemModsCanonicalHeaders.Select(h => (object)h).ToList() };
            var root = JsonNode.Parse(jsonFileText);
            var families = root is JsonObject o ? o["families"] as JsonArray : root as JsonArray;
            if (families == null)
                return rows;

            foreach (var famNode in families)
            {
                if (famNode is not JsonObject fam)
                    continue;
                var tiers = fam["tiers"] as JsonArray ?? new JsonArray();
                foreach (var tierNode in tiers)
                {
                    if (tierNode is not JsonObject tier)
                        continue;
                    var row = new List<object>();
                    foreach (string h in ItemModsCanonicalHeaders)
                        row.Add(ItemModsCell(fam, tier, h));
                    rows.Add(row);
                }
            }
            return rows;
        }

        private static object ItemModsCell(JsonObject fam, JsonObject tier, string header) => header switch
        {
            "family" or "pool" or "affix" or "kind" or "statType" or "template" or "description" => Str(fam[header]),
            "familyWeight" => Num(fam["weight"]),
            "integer" => fam["integer"]?.GetValue<bool>() == true ? "TRUE" : "FALSE",
            "slots" => JoinList(fam["slots"]),
            "parts" => JoinList(fam["parts"]),
            "tags" => JoinList(fam["tags"]),
            "keyword" or "maxRarity" => Str(tier[header]),
            "min" or "max" or "level" or "weight" => Num(tier[header]),
            "slotLevel" => tier["slotLevel"] is JsonObject sl
                ? string.Join(", ", sl.Select(kv => $"{kv.Key}:{Num(kv.Value)}"))
                : "",
            "tierSlots" => JoinList(tier["slots"]),
            _ => ""
        };

        /// <summary>ITEM MODS CSV → <c>ItemMods.json</c> text (object with <c>_doc</c> and <c>families</c>).</summary>
        public static string ItemModsCsvToJsonText(string csvContent)
        {
            var table = SimpleGameDataCsvParser.ParseToRows(csvContent);
            if (table.Count == 0)
                throw new InvalidOperationException("CSV has no rows.");
            var index = HeaderIndex(table[0]);

            var families = new JsonArray();
            JsonObject? current = null;
            string currentName = "";
            for (int r = 1; r < table.Count; r++)
            {
                var cells = table[r];
                string Cell(string h) => index.TryGetValue(h, out int i) && i < cells.Length ? (cells[i] ?? "").Trim() : "";
                string name = Cell("family");
                if (name.Length == 0)
                    continue;

                if (current == null || !string.Equals(name, currentName, StringComparison.Ordinal))
                {
                    current = new JsonObject { ["family"] = name };
                    SetString(current, "pool", Cell("pool").ToLowerInvariant());
                    SetString(current, "affix", Cell("affix").ToLowerInvariant());
                    SetString(current, "kind", Cell("kind").ToLowerInvariant());
                    SetString(current, "statType", Cell("statType"));
                    SetString(current, "template", Cell("template"));
                    SetString(current, "description", Cell("description"));
                    SetList(current, "parts", Cell("parts"));
                    SetList(current, "slots", Cell("slots"));
                    current["weight"] = ParseNumber(Cell("familyWeight"), 1);
                    SetList(current, "tags", Cell("tags"));
                    current["integer"] = Cell("integer").Equals("TRUE", StringComparison.OrdinalIgnoreCase);
                    current["tiers"] = new JsonArray();
                    families.Add(current);
                    currentName = name;
                }

                var tier = new JsonObject
                {
                    ["keyword"] = Cell("keyword"),
                    ["min"] = ParseNumber(Cell("min"), 0),
                    ["max"] = ParseNumber(Cell("max"), 0),
                    ["level"] = (int)Math.Round(ParseNumber(Cell("level"), 1)),
                    ["weight"] = ParseNumber(Cell("weight"), 100)
                };
                string slotLevel = Cell("slotLevel");
                if (slotLevel.Length > 0)
                {
                    var sl = new JsonObject();
                    foreach (var part in slotLevel.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
                    {
                        var kv = part.Split(':', 2, StringSplitOptions.TrimEntries);
                        if (kv.Length == 2 && int.TryParse(kv[1], NumberStyles.Integer, CultureInfo.InvariantCulture, out int lv))
                            sl[kv[0].ToLowerInvariant()] = lv;
                    }
                    if (sl.Count > 0)
                        tier["slotLevel"] = sl;
                }
                SetString(tier, "maxRarity", Cell("maxRarity"));
                SetList(tier, "slots", Cell("tierSlots"));
                ((JsonArray)current["tiers"]!).Add(tier);
            }

            var root = new JsonObject { ["_doc"] = ItemModsDocText, ["families"] = families };
            return root.ToJsonString(ItemModsJsonOptions) + System.Environment.NewLine;
        }

        // ---------- RARITY ----------

        private static List<IList<object>> BuildRarityPushValueRows(string jsonFileText)
        {
            var rows = new List<IList<object>> { RarityCanonicalHeaders.Select(h => (object)h).ToList() };
            if (JsonNode.Parse(jsonFileText) is not JsonArray arr)
                return rows;
            foreach (var node in arr)
            {
                if (node is not JsonObject r)
                    continue;
                var row = new List<object>();
                foreach (string h in RarityCanonicalHeaders)
                    row.Add(r[h] is JsonValue v && v.TryGetValue<string>(out var s) ? s : Num(r[h]));
                rows.Add(row);
            }
            return rows;
        }

        /// <summary>RARITY CSV → <c>RarityTable.json</c> text (one compact row per rarity).</summary>
        public static string RarityCsvToJsonText(string csvContent)
        {
            var table = SimpleGameDataCsvParser.ParseToRows(csvContent);
            if (table.Count == 0)
                throw new InvalidOperationException("CSV has no rows.");
            var index = HeaderIndex(table[0]);

            var lines = new List<string>();
            for (int r = 1; r < table.Count; r++)
            {
                var cells = table[r];
                string Cell(string h) => index.TryGetValue(h, out int i) && i < cells.Length ? (cells[i] ?? "").Trim() : "";
                string name = Cell("Name");
                if (name.Length == 0)
                    continue;
                var row = new JsonObject
                {
                    ["Name"] = name,
                    ["Weight"] = ParseNumber(Cell("Weight"), 0),
                    ["MinLevel"] = (int)Math.Round(ParseNumber(Cell("MinLevel"), 1)),
                    ["MinLines"] = (int)Math.Round(ParseNumber(Cell("MinLines"), 1)),
                    ["MaxLines"] = (int)Math.Round(ParseNumber(Cell("MaxLines"), 0)),
                    ["Explode"] = ParseNumber(Cell("Explode"), 0)
                };
                lines.Add("  " + row.ToJsonString(new JsonSerializerOptions { Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping }));
            }
            return "[" + System.Environment.NewLine + string.Join("," + System.Environment.NewLine, lines) + System.Environment.NewLine + "]" + System.Environment.NewLine;
        }

        // ---------- helpers ----------

        private static readonly JsonSerializerOptions ItemModsJsonOptions = new()
        {
            WriteIndented = true,
            Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping
        };

        private static Dictionary<string, int> HeaderIndex(string[] headerRow)
        {
            var index = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
            for (int i = 0; i < headerRow.Length; i++)
            {
                string h = (headerRow[i] ?? "").Trim().TrimStart('﻿');
                if (h.Length > 0 && !index.ContainsKey(h))
                    index[h] = i;
            }
            return index;
        }

        private static string Str(JsonNode? n) => n is JsonValue v && v.TryGetValue<string>(out var s) ? s : "";

        private static object Num(JsonNode? n)
        {
            if (n is not JsonValue v)
                return "";
            if (v.TryGetValue<double>(out var d))
                return d == Math.Floor(d) && Math.Abs(d) < 1e15 ? (object)(long)d : d;
            return v.TryGetValue<string>(out var s) ? s : "";
        }

        private static string JoinList(JsonNode? n) =>
            n is JsonArray a ? string.Join(", ", a.Select(x => Str(x)).Where(s => s.Length > 0)) : "";

        private static double ParseNumber(string cell, double fallback) =>
            double.TryParse(cell.Replace("%", ""), NumberStyles.Float, CultureInfo.InvariantCulture, out var d) ? d : fallback;

        private static void SetString(JsonObject o, string key, string value)
        {
            if (value.Length > 0)
                o[key] = value;
        }

        private static void SetList(JsonObject o, string key, string cell)
        {
            var parts = cell.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
            if (parts.Length > 0)
                o[key] = new JsonArray(parts.Select(p => (JsonNode)p).ToArray());
        }
    }
}
